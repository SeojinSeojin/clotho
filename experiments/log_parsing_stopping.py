"""K (2026-11-10): stopping rule from D's risk. Protocol: PROGRESS.md Decisions (H-M).

  cd experiments
  CLOTHO_MODEL=llama ../.venv/bin/python log_parsing_stopping.py run      # both parsers, every system, seeds 0-4
  CLOTHO_MODEL=gemma ../.venv/bin/python log_parsing_stopping.py run
  ../.venv/bin/python log_parsing_stopping.py report [--push]            -> reports/stopping_details.{md,json}

D x size reviews (batches of 5, up to 100). After each batch (and at N = 0): estimated remaining mis-parsed share =
sum over unreviewed groups of (1 - P(PASS)) x lines / all lines, with P raw or Platt-recalibrated on the reviewed
groups' verdicts (logistic regression of verdict on logit P once both classes are reviewed; raw before);
true remaining = 1 - PA_N.
"""
import os
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = "1"

import argparse
import json
import statistics
import sys
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP / "sharded"))
MODELS = {"llama": "", "gemma": "_gemma"}
NMAX, B = 100, 5
THR = (0.02, 0.05, 0.10)


def platt(p, rev, ver):
    from sklearn.linear_model import LogisticRegression
    y = np.array([ver[g] for g in rev], int)
    if len(set(y)) < 2:
        return p
    z = lambda q: np.log(np.clip(q, 1e-6, 1 - 1e-6) / (1 - np.clip(q, 1e-6, 1 - 1e-6)))  # noqa: E731
    m = LogisticRegression(C=1e6).fit(z(p[rev])[:, None], y)
    return m.predict_proba(z(p)[:, None])[:, 1]


def job(args):
    parser, system = args
    import logging
    import warnings
    logging.disable(logging.WARNING)
    warnings.filterwarnings("ignore")
    import log_parsing_triage as T
    seeds0 = {}
    if parser == "strong":
        import log_parsing_strong_sim as SS
        SS.install()
        seeds0 = {int(q): True for q in SS.strong_gen(system)["seeds"]}
    out = EXP / f"results_phase3{MODELS[T.MODEL]}" / "stopping" / parser / f"{system}.json"
    if out.exists():
        return str(out), "exists"
    d = T.stream(system)
    cache = T.cache_of(system, "base")
    ver = T.verdicts_of(system, "base")
    sizes = np.bincount(d["grp"], minlength=d["G"]).astype(float)
    src = T.source_data()
    res = {"system": system, "parser": parser, "n": d["n"], "runs": {}}
    for seed, fac in T.policies(system, "base", src, 10, ["dsize"])["dsize"]:
        pol = fac()
        pol.phase(np.ones(d["G"], bool), sizes)
        v, seq, rows = dict(seeds0), [], []
        while True:
            pol.t.verdicts = {pol.loc[g]: x for g, x in v.items()}
            p = np.asarray(pol.t.p_pass(), float)
            rev = sorted(v)
            unrev = np.array([g not in v for g in range(d["G"])])
            pc = platt(p, rev, v)
            true = 1 - T.curve(d, cache, seq)[-1] / d["n"]
            rows.append({"N": len(seq), "true": float(true),
                         "est_raw": float(((1 - p) * sizes)[unrev].sum() / d["n"]),
                         "est_platt": float(((1 - pc) * sizes)[unrev].sum() / d["n"])})
            if len(seq) >= NMAX or unrev.sum() == 0:
                break
            nxt = [g for g in pol.next(v) if g not in v][:NMAX - len(seq)]
            if not nxt:
                break
            for g in nxt:
                seq.append(int(g))
                v[int(g)] = bool(ver[g])
        res["runs"][seed] = rows
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res))
    return str(out), "done"


def run(workers):
    from multiprocessing import Pool
    import log_parsing_triage as T
    import log_parsing_strong as SG
    jobs = [("base", s) for s in T.SYSTEMS]
    if (SG.GEN / "chosen.json").exists():
        jobs += [("strong", s) for s in T.SYSTEMS if (SG.GEN / SG.chosen() / f"{s}.json").exists()]
    jobs.sort(key=lambda j: -T.stream(j[1])["G"])
    with Pool(min(workers, len(jobs))) as p:
        for r in p.imap_unordered(job, jobs):
            print(*r, flush=True)


def report(push=False):
    L = ["# K: stopping rule from D's risk (details)\n",
         "Generated by `log_parsing_stopping.py report`. Protocol: PROGRESS.md Decisions (H-M). Remaining = share of all "
         "lines still mis-parsed. Error = estimate minus true; runs = (system, seed). Precision of 'stop at the first N "
         "where the estimate < t' = share of runs whose true remaining at that N is < t (runs that never stop by N = 100 "
         "are counted separately). A row at N averages only runs that reached N (systems with fewer groups end earlier, so "
         "rows are not the same set of systems); when every group is reviewed the estimate is 0 and the run stops.\n"]
    J = {}
    for model, sfx in MODELS.items():
        for parser in ("base", "strong"):
            d = EXP / f"results_phase3{sfx}" / "stopping" / parser
            R = [json.loads(p.read_text()) for p in sorted(d.glob("*.json"))] if d.exists() else []
            if not R:
                continue
            key = f"{model}/{parser}"
            J[key] = jk = {"systems": len(R)}
            L.append(f"\n## {model}, {parser} parser ({len(R)} systems)\n")
            L.append("| N | true remaining (mean) | raw: mean abs err | raw: mean signed err | Platt: mean abs err | Platt: mean signed err |")
            L.append("|---|---|---|---|---|---|")
            for N in (0, 5, 10, 20, 50, 100):
                rows = [x for r in R for runs in r["runs"].values() for x in runs if x["N"] == N]
                if not rows:
                    continue
                e = {k: [x[k] - x["true"] for x in rows] for k in ("est_raw", "est_platt")}
                jk[N] = {"true": statistics.mean(x["true"] for x in rows), **{f"{k}_mae": statistics.mean(map(abs, v)) for k, v in e.items()},
                         **{f"{k}_bias": statistics.mean(v) for k, v in e.items()}, "n": len(rows)}
                L.append(f"| {N} | {jk[N]['true']:.3f} | {jk[N]['est_raw_mae']:.3f} | {jk[N]['est_raw_bias']:+.3f} | "
                         f"{jk[N]['est_platt_mae']:.3f} | {jk[N]['est_platt_bias']:+.3f} |")
            L.append("\n| estimator | threshold | runs stopping by 100 | precision (true < t at stop) | mean N at stop | mean true remaining at stop | reviews saved vs 100 |")
            L.append("|---|---|---|---|---|---|---|")
            for est in ("est_raw", "est_platt"):
                for t in THR:
                    stops = []
                    for r in R:
                        for runs in r["runs"].values():
                            hit = next((x for x in runs if x[est] < t), None)
                            stops.append(hit)
                    hits = [h for h in stops if h is not None]
                    prec = statistics.mean(h["true"] < t for h in hits) if hits else float("nan")
                    jk[f"{est}@{t}"] = {"stopped": len(hits), "runs": len(stops), "precision": prec,
                                        "mean_N": statistics.mean(h["N"] for h in hits) if hits else float("nan")}
                    L.append(f"| {est[4:]} | {t:.0%} | {len(hits)}/{len(stops)} | {prec:.2f} | "
                             + (f"{statistics.mean(h['N'] for h in hits):.1f} | {statistics.mean(h['true'] for h in hits):.3f} | "
                                f"{100 - statistics.mean(h['N'] for h in hits):.1f} |" if hits else " | | |"))
    (EXP / "reports" / "stopping_details.md").write_text("\n".join(L) + "\n")
    (EXP / "reports" / "stopping_details.json").write_text(json.dumps(J, indent=1, default=float))
    print("\n".join(L))
    if push:
        import hub_sync as hs
        files = {f"reports/stopping_details.{e}": EXP / "reports" / f"stopping_details.{e}" for e in ("md", "json")}
        for sfx in MODELS.values():
            files.update({str(p.relative_to(EXP)): p for p in (EXP / f"results_phase3{sfx}" / "stopping").rglob("*.json")})
        hs.commit_files(hs.get_results_repo(), files, "K stopping rule")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["run", "report"])
    ap.add_argument("-w", "--workers", type=int, default=14)
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    run(a.workers) if a.cmd == "run" else report(a.push)


if __name__ == "__main__":
    main()

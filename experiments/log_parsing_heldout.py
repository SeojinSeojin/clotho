"""Held-out headline: the Phase 3 final main table on the 10 systems not used for layer tuning.

  cd experiments && python log_parsing_heldout.py [--push]
  -> reports/log_parsing_heldout.{md,json}

Layer 16 was chosen on HDFS, Spark and Linux (log_parsing_tuning.py). This recomputes the fair_leakfree
macro means from the stored per-job JSON (results_phase3/final/fair_leakfree/, results_phase3/followups/ for
Clotho + output entropy) over the other 10 systems and puts them next to the 13-system values. No model or
GMM is rerun. Cells: per seed, mean over systems; then mean ± std over the 5 seeds. A system is dropped from
a split if any seed was skipped, as in the main table (none is under fair_leakfree).
"""
import argparse
import json
import statistics
import sys
from pathlib import Path

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP / "sharded"))
import log_parsing_phase3_final as F  # noqa: E402
import model_cfg as MC  # noqa: E402
import log_parsing_followups as FU  # noqa: E402

SETTING = "fair_leakfree"
TUNING = ["loghub_hdfs_500", "loghub_spark_500", "loghub_linux_500"]
HELDOUT = [d for d in F.SYSTEMS if d not in TUNING]
REFS = (100, 200)
METHODS = F.METHODS + ["clotho+out_entropy"]
NAMES = {**F.NAMES, "out_entropy": "Output entropy*", "clotho+out_entropy": "Clotho + output entropy*"}


def per_seed(R, RU, split, m, ref, systems):
    if m == "clotho+out_entropy":
        keep = [d for d in systems if (split, d) in RU and all("skipped" not in x for x in RU[(split, d)].values())]
        return FU.macro_seed(RU, split, m, ref, "auc", keep), len(keep)
    return F.macro(R, SETTING, split, m, ref, "auc", systems=systems)


def paired(a, b):
    d = [x - y for x, y in zip(a, b)]
    return f"{statistics.mean(d):+.3f} ± {statistics.stdev(d):.3f} (min {min(d):+.3f}, max {max(d):+.3f})" if d else "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    R, RU = F.load_all(), FU.load()
    J = {"heldout_systems": [F.SHORT(d) for d in HELDOUT]}
    cols = [(sp, r) for sp in F.SPLITS for r in REFS]
    L_ = [f"# Held-out headline: {len(HELDOUT)} systems not used for layer tuning ({MC.MODEL})\n",
          "Generated by `experiments/log_parsing_heldout.py` from the stored fair_leakfree jobs (balanced sampling, "
          "layer " + str(F.FAIR_LAYER) + ", label on samples 5-9, post-generation scores on samples 0-4). Layer " + str(F.FAIR_LAYER) + " was chosen on HDFS, "
          "Spark and Linux; the held-out columns exclude them. Cells: ROC-AUC, mean ± std over 5 seeds of the "
          "per-seed macro mean over systems. * = not a paper baseline (needs the generations).\n",
          f"Held-out systems: {', '.join(J['heldout_systems'])}.\n"]
    hdr = "| method | " + " | ".join(f"{sp} @{r} ({len(HELDOUT)} / {len(F.SYSTEMS)})" for sp, r in cols) + " |"
    L_ += [hdr, "|---" * (1 + len(cols)) + "|"]
    n = {}
    vals = {}
    for m in METHODS:
        cells = []
        for sp, r in cols:
            h, nh = per_seed(R, RU, sp, m, r, HELDOUT)
            f, nf = per_seed(R, RU, sp, m, r, F.SYSTEMS)
            vals[(m, sp, r, "held")], vals[(m, sp, r, "all")] = h, f
            n[sp] = (nh, nf)
            cells.append(f"{F.fmt(h)} / {F.fmt(f)}")
            J.setdefault("table", {}).setdefault(m, {})[f"{sp}@{r}"] = {"heldout": F.fmt(h), "all13": F.fmt(f)}
        L_.append(f"| {NAMES[m]} | " + " | ".join(cells) + " |")
    L_.append(f"\nSystems per split (held-out / all): standard {n['standard'][0]} / {n['standard'][1]}, "
              f"disjoint {n['disjoint'][0]} / {n['disjoint'][1]} (no split is skipped under fair_leakfree).\n")
    L_ += ["## Paired per-seed differences, held-out systems (mean ± std over seeds)\n",
           "| comparison | " + " | ".join(f"{sp} @{r}" for sp, r in cols) + " |", "|---" * (1 + len(cols)) + "|"]
    for b in ("MDSA", "lookup_drain", "out_entropy", "hybrid"):
        cells = [paired(vals[("clotho", sp, r, "held")], vals[(b, sp, r, "held")]) for sp, r in cols]
        L_.append(f"| Clotho minus {NAMES[b]} | " + " | ".join(cells) + " |")
        J.setdefault("paired_heldout", {})[b] = cells
    L_.append("")
    out = EXP / "reports" / f"log_parsing_heldout{MC.SUFFIX}.md"
    out.write_text("\n".join(L_) + "\n")
    out.with_suffix(".json").write_text(json.dumps(J, indent=1))
    print("\n".join(L_))
    if a.push:
        F._push([out, out.with_suffix(".json")])


if __name__ == "__main__":
    main()

"""Cross-system transfer under the main setting (fair_leakfree): reference set from system A, test = system B.

  cd experiments && python log_parsing_cross_fair.py [--workers 12] [--push]
  -> reports/log_parsing_cross_fair.{md,json}; per-job JSON in results_phase3/cross_fair/

Same 5 pairs and 5 seeds as log_parsing_phase3.py cross, but with the main config: balanced sampling (picks
only from A's inputs), layer 16 for Clotho/MDSA/GMMb, label from samples 5-9 (PASS if >= 3 of 5), output
entropy from samples 0-4. PCA is fitted on A + B + initial tests (label-free), as before. Test set = all 500
inputs of B; every method is scored on it.
Lookup (Drain): each system keeps its own Drain run (Loghub-2.0 settings, log_parsing_drain.py). logparser's
EventId is the md5 of the template string, so a B input finds A's group only if Drain produced the identical
template text in both systems; unseen -> overall failure rate of A's reference inputs. Lookup (oracle) uses
the Loghub templates (the pairs share none, so it is constant).
"""
import os
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = "1"

import argparse
import json
import logging
import statistics
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP / "sharded"))
import log_parsing_phase3_lib as L  # noqa: E402
import log_parsing_phase3_final as F  # noqa: E402
from log_parsing_phase3 import PAIRS  # noqa: E402

SETTING = "fair_leakfree"
OUT = EXP / "results_phase3" / "cross_fair"
REFS = (50, 100, 200)
METHODS = ["clotho", "MDSA", "GMMb", "lookup_drain", "lookup_oracle", "out_entropy", "random"]
NAMES = {"clotho": "Clotho", "MDSA": "MDSA", "GMMb": "GMMb", "lookup_drain": "Lookup (Drain)",
         "lookup_oracle": "Lookup (oracle)", "out_entropy": "Output entropy*", "random": "Random"}


def job(args):
    a, b, seed = args
    out = OUT / f"{F.SHORT(a)}__{F.SHORT(b)}" / f"seed{seed}.json"
    if out.exists():
        return str(out), "exists"
    logging.disable(logging.WARNING)
    cfg = F.SETTINGS[SETTING]
    sa, sb = F.system_data(a), F.system_data(b)
    Hi, Pi = F.initial_data(cfg["layer"])
    H = np.concatenate([F._hidden(a, cfg["layer"]), F._hidden(b, cfg["layer"]), Hi])
    na, nb = len(sa["P"]), len(sb["P"])
    sc = np.concatenate([F.label_scores(sa["P"], "leakfree"), F.label_scores(sb["P"], "leakfree"),
                         F.label_scores(Pi, "leakfree")])
    pseudo = [f"__initial_{i}__" for i in range(len(Hi))]
    tmpl = sa["templates"] + sb["templates"] + pseudo
    drain = sa["drain"] + sb["drain"] + pseudo
    init_idx = np.arange(na + nb, na + nb + len(Hi))
    pool, test = np.arange(na), np.arange(na, na + nb)
    oe = -np.array([F._entropy(p[:5]) for p in sb["parsed"]])
    np.random.seed(seed)
    runs = L.clotho_run(H, sc, init_idx, pool, test, seed, ref_sizes=REFS, method=cfg["method"])
    info = {"source": a, "target": b, "seed": seed, "shared_templates": len(set(sa["templates"]) & set(sb["templates"])),
            "shared_drain_groups": len(set(sa["drain"]) & set(sb["drain"])), "rows": []}
    y = sc[test] > L.PASS_THRESH
    for ref_n, r in sorted(runs.items()):
        ref = r["ref"]
        s = {"clotho": r["clotho"],
             "MDSA": L.surprise_adequacy(H, ref, test, sc, "MDSA", seed),
             "GMMb": L.surprise_adequacy(H, ref, test, sc, "MLSA", seed),
             "lookup_drain": L.template_lookup(ref, test, sc, drain, init_idx),
             "lookup_oracle": L.template_lookup(ref, test, sc, tmpl, init_idx),
             "out_entropy": oe, "random": np.random.RandomState(seed + 104729 + ref_n).rand(nb)}
        for m in METHODS:
            auc, top = (float("nan"), None) if s[m] is None else L.metrics(y, s[m], seed)
            info["rows"].append({"ref": ref_n, "method": m, "auc": auc, "fail_top50": top})
        info.setdefault("ref_pass", {})[str(ref_n)] = int((sc[ref] > L.PASS_THRESH).sum())
    info["n_test_pass"] = int(y.sum())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(info))
    return str(out), "ok"


def report(push=False):
    C = {}
    for f in sorted(OUT.glob("*/seed*.json")):
        d = json.loads(f.read_text())
        C.setdefault((d["source"], d["target"]), {})[d["seed"]] = d
    FR = F.load_all()
    J = {}
    L_ = ["# Cross-system transfer under the main setting (fair_leakfree)\n",
          "Generated by `experiments/log_parsing_cross_fair.py` (protocol in its docstring). Reference set from system "
          "A (balanced sampling, layer 16, label on samples 5-9), test = all 500 inputs of system B. Cells: ROC-AUC, "
          "mean ± std over 5 seeds (one pair per row, so no macro). `within B` = Clotho on B's standard split, same "
          "setting. * = needs the generations; reference-free, so it does not depend on A.\n"]
    for r in (100, 200):
        L_ += [f"## Reference size {r}\n",
               "| A -> B | shared templates | shared Drain groups | B PASS rate | " + " | ".join(NAMES[m] for m in METHODS)
               + " | Clotho within B (standard) |", "|---" * (5 + len(METHODS)) + "|"]
        for (a, b), runs in C.items():
            d0 = runs[0]
            cells = [F.fmt([F.val(d, m, r, "auc") for d in runs.values()]) for m in METHODS]
            within = F.fmt([F.val(d, "clotho", r, "auc") for d in FR[(SETTING, "standard", b)].values()])
            L_.append(f"| {F.SHORT(a)} -> {F.SHORT(b)} | {d0['shared_templates']} | {d0['shared_drain_groups']} | "
                      f"{d0['n_test_pass'] / 500:.1%} | " + " | ".join(cells) + f" | {within} |")
            J.setdefault(f"@{r}", {})[f"{F.SHORT(a)}->{F.SHORT(b)}"] = dict(zip(METHODS, cells), within_B=within)
        # macro over pairs per seed
        per = {m: [statistics.mean(F.val(C[p][s], m, r, "auc") for p in C) for s in F.SEEDS] for m in METHODS}
        L_.append("| **mean over 5 pairs** | | | | " + " | ".join(F.fmt(per[m]) for m in METHODS) + " | |")
        dd = lambda x, y_: [p - q for p, q in zip(per[x], per[y_])]  # noqa: E731
        L_.append(f"\nPaired per-seed, mean over pairs: Clotho minus MDSA {statistics.mean(dd('clotho', 'MDSA')):+.3f} ± "
                  f"{statistics.stdev(dd('clotho', 'MDSA')):.3f}; Clotho minus Lookup (Drain) "
                  f"{statistics.mean(dd('clotho', 'lookup_drain')):+.3f} ± {statistics.stdev(dd('clotho', 'lookup_drain')):.3f}.\n")
        J.setdefault("mean_over_pairs", {})[f"@{r}"] = {m: F.fmt(per[m]) for m in METHODS}
    out = EXP / "reports" / "log_parsing_cross_fair.md"
    out.write_text("\n".join(L_) + "\n")
    out.with_suffix(".json").write_text(json.dumps(J, indent=1))
    print("\n".join(L_))
    if push:
        F._push([OUT, out, out.with_suffix(".json")])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=12)
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--report_only", action="store_true")
    a = ap.parse_args()
    if not a.report_only:
        jobs = [(x, y, s) for x, y in PAIRS for s in F.SEEDS]
        with Pool(a.workers) as p:
            for path, status in p.imap_unordered(job, jobs):
                print(f"{status:>8}  {Path(path).relative_to(EXP)}", flush=True)
    report(a.push)


if __name__ == "__main__":
    main()

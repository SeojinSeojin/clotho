"""Aggregation for log_parsing_triage.py: reports/triage_details.{md,json} (the short reports/triage.md is written by hand
from these numbers). Macro mean over systems per seed, then mean ± std over seeds 0-4; deterministic orderings repeat
across seeds. Share fixed = (PA_N - PA_0) / (1 - PA_0); systems with PA_0 = 1 are skipped."""
import json
import math
import statistics
import sys
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP / "sharded"))

MODELS = {"llama": "", "gemma": "_gemma"}
SEEDS = [0, 1, 2, 3, 4]
NS = (5, 10, 20, 50, 100)
TUNE = ("HDFS", "Spark", "Linux")
NAMES = {"random": "Random", "frequent": "Most frequent", "newest": "Newest", "llmlog": "LLMLog confidence x size",
         "entropy": "Output entropy x size", "clotho": "Clotho alone", "dsize": "Transfer prior x size (no active)",
         "active_lookup": "Ours (active + lookup)", "triage": "TRIAGE", "oracle": "Oracle",
         "no_prior": "TRIAGE without prior", "no_freq": "TRIAGE without frequency", "no_prop": "TRIAGE without propagation",
         "prior_only": "Prior alone (no size)"}
E1 = ["random", "frequent", "newest", "llmlog", "entropy", "clotho", "dsize", "active_lookup", "triage", "oracle"]


def load(model, what, variant):
    d = EXP / f"results_phase3{MODELS[model]}" / "triage" / what / variant
    return {p.stem: json.loads(p.read_text()) for p in sorted(d.glob("*.json"))} if d.exists() else {}


def seed_runs(r, name):
    runs = r["runs"][name]
    return [runs.get(str(s), runs.get("0")) for s in SEEDS]


def share_at(pa, N, pa0):
    v = pa[min(N, len(pa) - 1)]
    return (v - pa0) / (1 - pa0)


def per_seed(R, name, fn, systems=None):
    """-> list over seeds of the macro mean over systems of fn(run, result)."""
    out = []
    for k in range(len(SEEDS)):
        v = [fn(seed_runs(r, name)[k], r) for s, r in R.items() if (systems is None or s in systems)
             and r["pa0"] < 1 and name in r["runs"]]
        v = [x for x in v if x is not None and not math.isnan(x)]
        out.append(float(np.mean(v)) if v else float("nan"))
    return out


def per_obs(R, name, fn, systems=None):
    """-> values per (system, seed) for SK-ESD / A12."""
    return [fn(seed_runs(r, name)[k], r) for s, r in R.items() if (systems is None or s in systems) and r["pa0"] < 1
            and name in r["runs"] for k in range(len(SEEDS))]


def ms(v):
    return f"{statistics.mean(v):.3f} ± {statistics.stdev(v):.3f}"


def sign_seeds(a, b):
    d = [x - y for x, y in zip(a, b)]
    m = statistics.mean(d)
    return f"{m:+.3f} ({sum((x > 0) == (m > 0) and x != 0 for x in d)}/5)"


def report(push=False):
    import log_parsing_stats as STT
    L = ["# TRIAGE details (cached-parser simulation, E1-E4)\n",
         "Generated by `experiments/log_parsing_triage.py report`. Protocol: PROGRESS.md Decisions (E; TRIAGE and E1-E5). "
         "Share = share of mis-parsed lines fixed (PA_N - PA_0) / (1 - PA_0); mean ± std over seeds 0-4 of the macro mean "
         "over systems; (k/5) = seeds on which TRIAGE minus the row has the sign of the mean. Held-out = systems other than "
         "HDFS, Spark, Linux.\n"]
    J = {}
    for model in MODELS:
        Rb, Ra = load(model, "e1", "base"), load(model, "e1", "ada")
        if not Rb:
            continue
        held = [s for s in Rb if s not in TUNE]
        J[model] = jm = {"systems": list(Rb), "held_out": held}
        ch = EXP / f"results_phase3{MODELS[model]}" / "triage" / "tune" / "chosen.json"
        jm["M"] = json.loads(ch.read_text()) if ch.exists() else None
        L.append(f"\n## {model} ({len(Rb)} systems; M = {jm['M']['M'] if jm['M'] else '?'}, tuning scores {jm['M']['scores'] if jm['M'] else ''})\n")
        L.append("| system | lines | groups | groups correct (greedy) | PA_0 | PA_0 AdaParser | wrong groups |")
        L.append("|---|---|---|---|---|---|---|")
        for s, r in Rb.items():
            L.append(f"| {s} | {r['n_lines']} | {r['G']} | {r['greedy_correct_groups']:.3f} | {r['pa0']:.3f} | "
                     f"{Ra[s]['pa0']:.3f} | {round((1 - r['greedy_correct_groups']) * r['G'])} |" if s in Ra else "")
        jm["pa0"] = {"base": statistics.mean(r["pa0"] for r in Rb.values()),
                     "ada": statistics.mean(r["pa0"] for r in Ra.values()) if Ra else None}
        L.append(f"\nMacro PA_0: greedy cache {jm['pa0']['base']:.3f}, AdaParser-corrected cache {jm['pa0']['ada']:.3f}.\n")
        for tag, R in (("base", Rb), ("ada", Ra)):
            for subset, systems in (("all", None), ("held-out", held)):
                names = [n for n in E1 + ["no_prior", "no_freq", "no_prop", "prior_only"] if n in next(iter(R.values()))["runs"]]
                L.append(f"\n### E1 {'greedy cache' if tag == 'base' else 'AdaParser-corrected cache'}, {subset} systems: share fixed\n")
                L.append("| ordering | " + " | ".join(f"N={n}" for n in NS) + " | TRIAGE minus row @20 | lines fixed / review @20 | share of oracle @20 |")
                L.append("|---|" + "---|" * (len(NS) + 3))
                tri20 = per_seed(R, "triage", lambda x, r: share_at(x["pa"], 20, r["pa0"]), systems)
                orc20 = per_seed(R, "oracle", lambda x, r: share_at(x["pa"], 20, r["pa0"]), systems)
                for nm in names:
                    cells = []
                    for N in NS:
                        v = per_seed(R, nm, lambda x, r, N=N: share_at(x["pa"], N, r["pa0"]), systems)
                        cells.append(ms(v))
                        jm.setdefault(f"e1/{tag}/{subset}", {}).setdefault(nm, {})[N] = v
                    v20 = per_seed(R, nm, lambda x, r: share_at(x["pa"], 20, r["pa0"]), systems)
                    lpr = per_seed(R, nm, lambda x, r: (x["pa"][min(20, len(x["pa"]) - 1)] - r["pa0"]) * r["n_lines"] / 20, systems)
                    frac = [a / b for a, b in zip(v20, orc20)]
                    jm.setdefault(f"e1/{tag}/{subset}/frac_oracle", {})[nm] = frac
                    jm.setdefault(f"e1/{tag}/{subset}/lines_per_review", {})[nm] = lpr
                    L.append(f"| {NAMES[nm]} | " + " | ".join(cells) + f" | {sign_seeds(tri20, v20) if nm != 'triage' else ''} | "
                             f"{statistics.mean(lpr):.1f} | {ms(frac)} |")
                if subset == "all":
                    obs = {nm: per_obs(R, nm, lambda x, r: share_at(x["pa"], 20, r["pa0"])) for nm in names if nm != "oracle"}
                    rk = STT.sk_esd(obs)
                    order = sorted(obs, key=lambda m: (rk[m], -np.mean(obs[m])))
                    L.append("\nSK-ESD @20 over (system, seed): " + "; ".join(f"{rk[m]}. {NAMES[m]} {np.mean(obs[m]):.3f}" for m in order))
                    a = {b: STT.a12(obs["triage"], obs[b]) for b in obs if b != "triage"}
                    L.append("\nA12 TRIAGE vs: " + "; ".join(f"{NAMES[b]} {v:.2f} ({STT.magnitude(v)})" for b, v in a.items()))
                    jm[f"e1/{tag}/sk"] = {m: rk[m] for m in order}
                    jm[f"e1/{tag}/a12"] = a
            if tag == "base":
                # E3 cold start
                L.append("\n### E3 cold start (greedy cache): lines fixed after N reviews (macro mean over systems) and share fixed\n")
                L.append("| ordering | " + " | ".join(f"N={n}" for n in range(1, 11)) + " |")
                L.append("|---|" + "---|" * 10)
                for nm in ("prior_only", "dsize", "frequent", "triage", "random", "oracle"):
                    if nm not in next(iter(R.values()))["runs"]:
                        continue
                    row = []
                    for N in range(1, 11):
                        v = per_seed(R, nm, lambda x, r, N=N: share_at(x["pa"], N, r["pa0"]))
                        row.append(f"{statistics.mean(v):.3f}")
                        jm.setdefault("e3", {}).setdefault(nm, {})[N] = v
                    L.append(f"| {NAMES[nm]} | " + " | ".join(row) + " |")
                for a_, b_ in (("prior_only", "frequent"), ("dsize", "frequent")):
                    L.append(f"\n{NAMES[a_]} minus Most frequent, share fixed: " + ", ".join(
                        f"N={N} {sign_seeds(jm['e3'][a_][N], jm['e3'][b_][N])}" for N in (1, 3, 5, 10)))
        # E4 drift
        R4 = load(model, "e4", "base")
        if R4:
            L.append("\n### E4 drift (greedy cache; half the reviews at the midpoint, half at the end)\n")
            L.append("Share of mis-parsed lines fixed among lines of groups first seen in the second half (systems with such "
                     "mis-parsed lines), and over all lines.\n")
            L.append("| ordering | " + " | ".join(f"new N={n}" for n in (10, 20, 50, 100)) + " | " + " | ".join(f"all N={n}" for n in (10, 20, 50, 100)) + " |")
            L.append("|---|" + "---|" * 8)

            def f_new(x, r, N):
                q = x[str(N)]
                miss = q["new2_lines"] - q["new2_base"]
                return (q["new2"] - q["new2_base"]) / miss if miss > 0 else None

            def f_all(x, r, N):
                return (x[str(N)]["all"] - r["pa0"]) / (1 - r["pa0"])
            for nm in ("random", "frequent", "newest", "llmlog", "clotho", "dsize", "triage", "oracle"):
                if nm not in next(iter(R4.values()))["runs"]:
                    continue
                c1, c2 = [], []
                for N in (10, 20, 50, 100):
                    v1 = per_seed(R4, nm, lambda x, r, N=N: f_new(x, r, N))
                    v2 = per_seed(R4, nm, lambda x, r, N=N: f_all(x, r, N))
                    jm.setdefault("e4/new", {}).setdefault(nm, {})[N] = v1
                    jm.setdefault("e4/all", {}).setdefault(nm, {})[N] = v2
                    c1.append(ms(v1))
                    c2.append(ms(v2))
                L.append(f"| {NAMES[nm]} | " + " | ".join(c1) + " | " + " | ".join(c2) + " |")
            for b_ in ("frequent", "dsize", "llmlog", "random"):
                if b_ in jm["e4/new"]:
                    L.append(f"\nTRIAGE minus {NAMES[b_]} (new-template lines): " + ", ".join(
                        f"N={N} {sign_seeds(jm['e4/new']['triage'][N], jm['e4/new'][b_][N])}" for N in (10, 20, 50, 100)))
        # cost
        import json as _j
        tim = EXP / "data" / "stream_hidden" / model / "timing.json"
        G = {s: r["G"] for s, r in Rb.items()}
        gen_dir = EXP / "data" / "stream_gen" / model
        ada = [_j.loads((gen_dir / f"{s}.json").read_text())["wall_s_adaparser_per_template"] for s in Rb]
        gre = [_j.loads((gen_dir / f"{s}.json").read_text())["wall_s_greedy_per_template"] for s in Rb]
        hid = [_j.loads(tim.read_text())[s]["s_per_template"] for s in Rb] if tim.exists() else []
        tri = []
        for s, r in Rb.items():
            w = [x["wall_s"] for x in r["runs"]["triage"].values()]
            tri.append(statistics.mean(w) / G[s])
        jm["cost"] = {"adaparser_s_per_template": statistics.mean(ada), "greedy_batched_s_per_template": statistics.mean(gre),
                      "hidden_hf_s_per_template": statistics.mean(hid) if hid else None,
                      "triage_cpu_s_per_template": statistics.mean(tri)}
        L.append(f"\n### Cost per new template (macro mean over systems)\n\nAdaParser corrector (vLLM, batched over the "
                 f"system's templates): {jm['cost']['adaparser_s_per_template']*1000:.0f} ms; greedy parse (vLLM, batched): "
                 f"{jm['cost']['greedy_batched_s_per_template']*1000:.0f} ms; hidden state as a separate HF forward pass "
                 f"(unbatched): {(jm['cost']['hidden_hf_s_per_template'] or 0)*1000:.0f} ms (free if the parser's prefill exposes it); "
                 f"TRIAGE CPU (prior PCA + 20 refits + queue for 100 reviews, one process) per template: "
                 f"{jm['cost']['triage_cpu_s_per_template']*1000:.0f} ms.")
    (EXP / "reports" / "triage_details.md").write_text("\n".join(L) + "\n")
    (EXP / "reports" / "triage_details.json").write_text(json.dumps(J, indent=1))
    print("\n".join(L))
    if push:
        import hub_sync as hs
        files = {f"reports/triage_details.{e}": EXP / "reports" / f"triage_details.{e}" for e in ("md", "json")}
        for model in MODELS:
            d = EXP / f"results_phase3{MODELS[model]}" / "triage"
            for p in d.rglob("*.json"):
                files[str(p.relative_to(EXP))] = p
        hs.commit_files(hs.get_results_repo(), files, "triage results and report")

"""PASS rates per system for the current CLOTHO_MODEL (rules_template, strict_match) under both labels,
and the 10-90% drop rule of 2026-11-07 (original label: PASS if > 5 of 10 strict matches).

  cd experiments && CLOTHO_MODEL=gemma python log_parsing_pass_rates.py   # -> reports/log_parsing_pass_rates_<model>.md
"""
import json
import sys
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
import model_cfg as MC  # noqa: E402
from clotho.exp_config import supported_datasets  # noqa: E402
from clotho.dataset.log_parsing.output_parsers import score_output  # noqa: E402

T = "rules_template"
rows, drop = [], []
for ds in supported_datasets["log_parsing"]:
    f = EXP / f"data/results_{MC.MODEL}/log_parsing/inference_results/{T}/{ds}_R10_T0.8.json"
    if not f.exists():
        rows.append(f"| {ds} | not generated | | | |")
        continue
    g = json.load(open(f))
    P = np.array([[score_output(o, x["GT"], T)["strict_match"] for o in x["inferences"]] for x in g], dtype=bool)
    orig = (P.sum(1) > 5).mean()
    lf = (P[:, 5:].sum(1) >= 3).mean()
    keep = 0.10 <= orig <= 0.90
    if not keep:
        drop.append(ds)
    rows.append(f"| {ds} | {orig:.1%} | {lf:.1%} | {P.mean():.1%} | {'keep' if keep else 'DROP'} |")
out = [f"# PASS rates, {MC.MODEL}, rules_template, strict_match\n",
       "Generated by `experiments/log_parsing_pass_rates.py`. Drop rule (fixed 2026-11-07 for Llama): keep a system only "
       "if 10-90% of its inputs PASS under the original label (> 5 of 10 strict matches).\n",
       "| system | PASS (> 5 of 10) | PASS (>= 3 of samples 5-9) | per-sample strict accuracy | decision |",
       "|---|---|---|---|---|"] + rows + ["", "Dropped: " + (", ".join(drop) or "none")]
p = EXP / "reports" / f"log_parsing_pass_rates{MC.SUFFIX or '_llama'}.md"
p.write_text("\n".join(out) + "\n")
print("\n".join(out))

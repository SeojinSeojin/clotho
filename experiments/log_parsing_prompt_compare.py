"""Prompt comparison with seeds: Clotho and template lookup under messages_template vs rules_template.

  cd experiments && python log_parsing_prompt_compare.py [--workers 12]
  -> reports/log_parsing_prompt_compare.{md,json}

Same protocol for both prompts: standard split, random sampling, layer 21 (the only layer with
messages_template hidden states), original label (> 5 of 10 strict matches), 5 seeds, harness
log_parsing_phase3_lib (verified identical to the core loop). Each prompt uses its own initial set.
"""
import os
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = "1"

import argparse
import json
import logging
import statistics
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
import log_parsing_phase3_lib as L  # noqa: E402
from log_parsing_phase3 import SYSTEMS, SHORT  # noqa: E402

TEMPLATES = ["messages_template", "rules_template"]
SEEDS = [0, 1, 2, 3, 4]


def job(args):
    template, ds, seed = args
    logging.disable(logging.WARNING)
    s = L.load_system(ds, template)
    H, sc, tp, en, off, init_idx = L.assemble([s], L.load_initial(template))
    np.random.seed(seed)
    runs = L.clotho_run(H, sc, init_idx, off[ds], None, seed)
    out = {"template": template, "system": ds, "seed": seed, "n_pass": int((s["scores"] > L.PASS_THRESH).sum())}
    for ref_n, r in runs.items():
        y = sc[r["test"]] > L.PASS_THRESH
        out[str(ref_n)] = {
            "clotho": float("nan") if r["clotho"] is None else L.metrics(y, r["clotho"], seed)[0],
            "lookup": L.metrics(y, L.template_lookup(r["ref"], r["test"], sc, tp, init_idx), seed)[0]}
    return out


def ms(xs):
    xs = [x for x in xs if not np.isnan(x)]
    return f"{statistics.mean(xs):.3f} ± {statistics.stdev(xs):.3f}" if len(xs) > 1 else "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=12)
    a = ap.parse_args()
    with Pool(a.workers) as p:
        res = p.map(job, [(t, ds, s) for t in TEMPLATES for ds in SYSTEMS for s in SEEDS])
    R = {}
    for r in res:
        R.setdefault((r["template"], r["system"]), []).append(r)
    L_ = ["# log_parsing prompt comparison: messages_template vs rules_template (5 seeds)\n",
          "Standard split, random sampling, layer 21, label > 5 of 10 strict matches. ROC-AUC mean ± std over seeds. "
          "Generated by `experiments/log_parsing_prompt_compare.py`.\n"]
    summary = {}
    for ref in (100, 200):
        L_ += [f"## Reference size {ref}\n",
               "| system | PASS msg / rules | Clotho msg | Clotho rules | Lookup msg | Lookup rules |",
               "|---|---|---|---|---|---|"]
        per = {}            # system -> seed means; only systems where every column is defined enter the mean
        excluded = []
        for ds in SYSTEMS:
            m, r = R[("messages_template", ds)], R[("rules_template", ds)]
            cells = {"cm": [x[str(ref)]["clotho"] for x in m], "cr": [x[str(ref)]["clotho"] for x in r],
                     "lm": [x[str(ref)]["lookup"] for x in m], "lr": [x[str(ref)]["lookup"] for x in r]}
            means = {k: statistics.mean([x for x in v if not np.isnan(x)] or [float("nan")]) for k, v in cells.items()}
            if any(np.isnan(v) for v in means.values()):
                excluded.append(SHORT(ds))
            else:
                per[ds] = means
            L_.append(f"| {SHORT(ds)} | {m[0]['n_pass']} / {r[0]['n_pass']} | " + " | ".join(ms(cells[k]) for k in ("cm", "cr", "lm", "lr")) + " |")
        avg = {k: statistics.mean(v[k] for v in per.values()) for k in ("cm", "cr", "lm", "lr")}
        wins = int(sum(bool(v["cm"] > v["cr"]) for v in per.values()))
        L_.append(f"| **mean over {len(per)} systems** | | " + " | ".join(f"{avg[k]:.3f}" for k in ("cm", "cr", "lm", "lr")) + " |")
        L_.append(f"\nClotho higher under messages_template on {wins} of {len(per)} systems (seed means). "
                  f"Excluded from the mean (a column undefined: Clotho never had 10 passing references): "
                  f"{', '.join(excluded) or 'none'}.\n")
        summary[ref] = avg | {"clotho_msg_wins": wins, "n_systems": len(per), "excluded": excluded}
    (EXP / "reports" / "log_parsing_prompt_compare.md").write_text("\n".join(L_) + "\n")
    (EXP / "reports" / "log_parsing_prompt_compare.json").write_text(json.dumps(summary, indent=1))
    print("\n".join(L_))


if __name__ == "__main__":
    main()

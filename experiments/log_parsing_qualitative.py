"""Qualitative examples: failures Clotho ranks as likely PASS (top 10%) and as likely FAIL (bottom 30%).

  cd experiments && python log_parsing_qualitative.py [--push]   -> reports/log_parsing_qualitative.md

Main setting fair_leakfree, standard split, seed 0, reference size 100 (choices fixed before looking).
Clotho is recomputed (test set asserted equal to the stored job). Ranks are over Clotho's test set by Clotho
score (high = likely PASS). Failure = label FAIL (fewer than 3 of samples 5-9 match exactly).
  missed  (top 10%): the 5 failing test inputs with the highest Clotho scores.
  caught  (bottom 30%): 5 failing test inputs drawn uniformly (RandomState(0)) from the bottom 30%.
Model output shown = the most frequent parsed template among samples 5-9 (the label samples), with its count.
"In ref" = the input's Loghub template occurs among the non-initial reference inputs (and how many of those
references PASS).
"""
import os
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = "1"
import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP / "sharded"))
import log_parsing_phase3_lib as L  # noqa: E402
import log_parsing_phase3_final as F  # noqa: E402

SETTING, SPLIT, SEED, REF = "fair_leakfree", "standard", 0, 100
SYSTEMS = ["loghub_hdfs_500", "loghub_hadoop_500"]


def esc(s, n=160):
    s = "<PARSE_FAILURE>" if s is None else str(s)
    s = s if len(s) <= n else s[:n] + "…"
    return "`" + s.replace("|", "\\|").replace("`", "'") + "`"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    L_ = ["# Qualitative examples: HDFS and Hadoop\n",
          "Generated by `experiments/log_parsing_qualitative.py` (selection rule in its docstring): fair_leakfree, "
          "standard split, seed 0, reference size 100. Rank = position among Clotho's test inputs by Clotho score "
          "(1 = most likely PASS). Every row is a FAIL under the label (samples 5-9). `in ref` = the Loghub "
          "template occurs in the reference set (passing / total such references).\n"]
    J = {}
    for ds in SYSTEMS:
        stored = json.loads(F.job_path(SETTING, SPLIT, ds, SEED).read_text())
        B = F.build(ds, SETTING)
        H, sc, init_idx, idx = B["H"], B["sc"], B["init_idx"], np.arange(B["n"])
        np.random.seed(SEED)
        r = L.clotho_run(H, sc, init_idx, idx, None, SEED, method=F.SETTINGS[SETTING]["method"])[REF]
        t, ref, c = np.asarray(r["test"]), np.asarray(r["ref"]), np.asarray(r["clotho"])
        assert list(t) == stored["runs"][str(REF)]["test"]
        order = np.argsort(-c, kind="stable")
        rank = np.empty(len(t), int)
        rank[order] = np.arange(1, len(t) + 1)
        fail = sc[t] <= L.PASS_THRESH
        n = len(t)
        top = [i for i in order[: int(np.ceil(0.10 * n))] if fail[i]][:5]
        bottom_pool = [i for i in order[n - int(np.ceil(0.30 * n)):] if fail[i]]
        bottom = sorted(np.random.RandomState(0).choice(bottom_pool, size=5, replace=False).tolist(), key=lambda i: rank[i])
        src = [json.loads(l) for l in open(L.SUITES / f"{ds}.jsonl")]
        s = F.system_data(ds)
        refs = [i for i in ref if i not in set(init_idx.tolist())]
        auc = L.metrics(~fail, c, SEED)[0]
        n_top_fail = int(sum(fail[i] for i in order[: int(np.ceil(0.10 * n))]))
        n_bot_fail = int(len(bottom_pool))
        L_ += [f"## {F.SHORT(ds)}\n",
               f"Test inputs {n} ({int(fail.sum())} FAIL), Clotho ROC-AUC {auc:.3f}. Failures in the top 10% "
               f"({int(np.ceil(0.10 * n))} inputs): {n_top_fail}; in the bottom 30% ({int(np.ceil(0.30 * n))} inputs): "
               f"{n_bot_fail}." + (f" Only {len(top)} failures fall in the top 10%; all are shown." if len(top) < 5 else "") + "\n",
               "| group | rank | input | ground truth | model output (samples 5-9, most frequent) | matches 5-9 | in ref |",
               "|---|---|---|---|---|---|---|"]
        for grp, sel in (("missed (top 10%)", top), ("caught (bottom 30%)", bottom)):
            for i in sel:
                g = int(t[i])
                outs = s["parsed"][g][5:]
                mc, cnt = Counter("<PARSE_FAILURE>" if o is None else o for o in outs).most_common(1)[0]
                tm = B["templates"][g]
                same = [j for j in refs if B["templates"][j] == tm]
                inref = f"yes ({sum(sc[j] > L.PASS_THRESH for j in same)}/{len(same)})" if same else "no"
                L_.append(f"| {grp} | {rank[i]} | {esc(src[g]['content'])} | {esc(tm)} | {esc(mc)} ({cnt}/5) | "
                          f"{int(s['P'][g][5:].sum())}/5 | {inref} |")
                J.setdefault(F.SHORT(ds), []).append({"group": grp, "rank": int(rank[i]), "input_index": g,
                                                      "in_ref": inref})
        L_.append("")
    out = EXP / "reports" / "log_parsing_qualitative.md"
    out.write_text("\n".join(L_) + "\n")
    out.with_suffix(".json").write_text(json.dumps(J, indent=1))
    print("\n".join(L_))
    if a.push:
        F._push([out, out.with_suffix(".json")])


if __name__ == "__main__":
    main()

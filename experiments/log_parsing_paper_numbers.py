def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    out = REP / "paper_numbers.md"
    out.write_text("\n".join(build()) + "\n")
    print(out.read_text())
    if a.push:
        F._push([out])


if __name__ == "__main__":
    main()

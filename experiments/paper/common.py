def short(ds):
    return ds.replace("loghub_", "").replace("_nat500", "").replace("_500", "")


def rp(model):
    return EXP / f"results_phase3{SUFFIX[model]}"


def _load(paths, key):
    R = {}
    for f in sorted(paths):
        d = json.loads(f.read_text())
        R.setdefault(d[key], {})[d["seed"]] = d
    return R


def capped(model, setting="fair_leakfree", split="standard"):
    """{system: {seed: job}} from log_parsing_phase3_final.py (template-capped 500-message suites)."""
    R = _load((rp(model) / "final" / setting / split).glob("*/seed*.json"), "system")
    return {ds: v for ds, v in R.items() if short(ds) not in DROPPED[model]}


def followups(model, split="standard"):
    R = _load((rp(model) / "followups" / split).glob("*/seed*.json"), "system")
    return {ds: v for ds, v in R.items() if short(ds) not in DROPPED[model]}


def natural(model):
    """{system name: {seed: job}} from log_parsing_natural.py (kept systems only)."""
    R = _load((rp(model) / "natural13").glob("*/seed*.json"), "system")
    kept = json.loads((EXP / "reports" / f"log_parsing_natural13{SUFFIX[model]}.json").read_text())["kept"]
    return {s: R[s] for s in kept}


def row_val(d, m, ref):
    for r in d.get("rows", []):
        if r["method"] == m and r["ref"] == ref:
            v = r["auc"]
            return None if v is None or v != v else v
    return None


def kept_systems(R):
    return [s for s, v in R.items() if len(v) == len(SEEDS) and not any("skipped" in d for d in v.values())]


def macro(R, m, ref, getter=row_val):
    """Per-seed macro mean over the systems kept on every seed; None if a value is missing."""
    ks = kept_systems(R)
    out = []
    for k in SEEDS:
        xs = [getter(R[s][k], m, ref) for s in ks]
        if not xs or any(x is None for x in xs):
            return None
        out.append(statistics.mean(xs))
    return out


def fu_val(d, m, ref):
    v = d.get("refs", {}).get(str(ref), {}).get(m, {}).get("auc")
    return None if v is None or v != v else v


def fmt(xs, bold=False):
    if xs is None:
        return "--"
    s = f"{statistics.mean(xs):.3f} $\\pm$ {statistics.stdev(xs):.3f}"
    return f"\\textbf{{{s}}}" if bold else s


def best_key(col):
    """col: {key: per-seed list or None}. Key of the best mean if it beats the runner-up on every seed."""
    c = {k: v for k, v in col.items() if v is not None}
    if len(c) < 2:
        return None
    order = sorted(c, key=lambda k: statistics.mean(c[k]), reverse=True)
    a, b = c[order[0]], c[order[1]]
    return order[0] if all(x > y for x, y in zip(a, b)) else None


def table(path, script, caption, label, colspec, header, body):
    tex = [f"% Generated by experiments/paper/{script}; do not edit.",
           "\\begin{table*}[t]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", *header, "\\midrule", *body, "\\bottomrule",
           "\\end{tabular}", "\\end{table*}"]
    Path(path).write_text("\n".join(tex) + "\n")
    print("\n".join(tex))



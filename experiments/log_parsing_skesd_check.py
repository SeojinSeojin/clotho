"""M (2026-11-10): our Python Scott-Knott ESD (log_parsing_stats.sk_esd) vs the CRAN ScottKnottESD package.
Protocol: PROGRESS.md Decisions (H-M).

  cd experiments && ../.venv/bin/python log_parsing_skesd_check.py export
  Rscript log_parsing_skesd_r.R data/skesd_check
  ../.venv/bin/python log_parsing_skesd_check.py compare [--push]    -> reports/skesd_check.{md,json}

Matrices: the main tables (capped standard and natural, @100 and @200, both models) exactly as log_parsing_stats ranks
them (methods with >= 10 observations; methods whose count differs from the most common count are dropped and listed,
since the R package needs a rectangular frame), and E1 @20 (TRIAGE) and F2 @20 (strong parser) share fixed.
"""
import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
sys.path.insert(0, str(EXP))
import log_parsing_stats as S  # noqa: E402

D = EXP / "data" / "skesd_check"


def matrices():
    out = {}
    for model, (suf, _) in S.MODELS.items():
        for ref in (100, 200):
            out[f"{model}_main_capped_{ref}"] = S.main_table(suf, ref)
            out[f"{model}_main_natural_{ref}"] = S.natural(suf, ref)
    import log_parsing_triage_report as TR
    import log_parsing_strong_sim as SS
    for model in ("llama", "gemma"):
        R = TR.load(model, "e1", "base")
        if R:
            names = [n for n in TR.E1 if n != "oracle"]
            out[f"{model}_triage_e1_20"] = {n: TR.per_obs(R, n, lambda x, r: TR.share_at(x["pa"], 20, r["pa0"])) for n in names}
        R = SS.load(model, "strong")
        if R:
            out[f"{model}_strong_f2_20"] = {n: [SS.share(SS.runs_of(r, n)[k], r, 20) for r in R.values() if r["pa0"] < 1 for k in range(5)]
                                            for n in SS.ORD if n != "oracle"}
    return out


def export():
    import pandas as pd
    D.mkdir(parents=True, exist_ok=True)
    meta = {}
    for name, data in matrices().items():
        data = {m: v for m, v in data.items() if len(v) >= 10}
        if not data:
            continue
        n = Counter(len(v) for v in data.values()).most_common(1)[0][0]
        drop = [m for m, v in data.items() if len(v) != n]
        data = {m: v for m, v in data.items() if len(v) == n}
        pd.DataFrame(data).to_csv(D / f"{name}.csv", index=False)
        meta[name] = {"n": n, "dropped": drop, "py": S.sk_esd(data), "means": {m: float(np.mean(v)) for m, v in data.items()}}
    (D / "meta.json").write_text(json.dumps(meta, indent=1))
    print(len(meta), "matrices")


def compare(push=False):
    meta = json.loads((D / "meta.json").read_text())
    L = ["# M: Python Scott-Knott ESD vs the R package ScottKnottESD (details)\n",
         "Generated by `log_parsing_skesd_check.py`. Protocol: PROGRESS.md Decisions (H-M). R `sk_esd(version='p')` is the "
         "parametric original our reimplementation follows; `version='np'` is the package default. Rank 1 = best.\n",
         "| matrix | obs / method | methods | identical ranks to R p | identical to R np | differing methods (Python / R p / R np) |",
         "|---|---|---|---|---|---|"]
    J = {}
    tot = {"p": [0, 0], "np": [0, 0]}
    pairs = {"same relation": 0, "R separates, Python merges": 0, "Python separates, R merges": 0, "inverted": 0}
    for name, m in meta.items():
        r = json.loads((D / f"{name}.r.json").read_text())
        py = m["py"]
        diff = [k for k in py if py[k] != r["p"].get(k) or py[k] != r["np"].get(k)]
        same = {v: sum(py[k] == r[v].get(k) for k in py) for v in ("p", "np")}
        for v in ("p", "np"):
            tot[v][0] += same[v]
            tot[v][1] += len(py)
        ms_ = list(py)
        for i, a in enumerate(ms_):
            for b in ms_[i + 1:]:
                dp, dr = np.sign(py[a] - py[b]), np.sign(r["p"][a] - r["p"][b])
                k = ("same relation" if dp == dr else "R separates, Python merges" if dp == 0 else
                     "Python separates, R merges" if dr == 0 else "inverted")
                pairs[k] += 1
        J[name] = {"py": py, "r_p": r["p"], "r_np": r["np"], "dropped": m["dropped"], "version": r["version"]}
        L.append(f"| {name} | {m['n']} | {len(py)} | {same['p']}/{len(py)} | {same['np']}/{len(py)} | "
                 + "; ".join(f"{k} {py[k]}/{r['p'].get(k)}/{r['np'].get(k)}" for k in diff) + " |")
        if m["dropped"]:
            L.append(f"| (dropped from {name}: unequal counts) | | {', '.join(m['dropped'])} | | | |")
    L.append("\nPairwise (method pairs within a matrix, Python vs R 'p'): " + ", ".join(f"{k} {v}" for k, v in pairs.items()) + ".")
    J["pairs"] = pairs
    L.append(f"\nOverall: {tot['p'][0]}/{tot['p'][1]} method ranks identical to R 'p', {tot['np'][0]}/{tot['np'][1]} to R 'np' "
             f"(ScottKnottESD {r['version']}).")
    J["total"] = tot
    (EXP / "reports" / "skesd_check.md").write_text("\n".join(L) + "\n")
    (EXP / "reports" / "skesd_check.json").write_text(json.dumps(J, indent=1))
    print("\n".join(L))
    if push:
        import hub_sync as hs
        hs.commit_files(hs.get_results_repo(), {f"reports/skesd_check.{e}": EXP / "reports" / f"skesd_check.{e}" for e in ("md", "json")}, "M SK-ESD check")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["export", "compare"])
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    export() if a.cmd == "export" else compare(a.push)
